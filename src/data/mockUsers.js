export const mockApprenants = mockUsers
  .filter((u) => u.role === 'apprenant')
  .map((apprenant) => {
    // Add computed fields for the learners management page
    const formationPrincipale = apprenant.formations && apprenant.formations.length > 0
      ? apprenant.formations[0]
      : '—';
    const progress = apprenant.id === 1 ? 78
      : apprenant.id === 'student-1' ? 66
      : apprenant.id === 'student-2' ? 54
      : apprenant.id === 'student-3' ? 100
      : apprenant.id === 'student-4' ? 45
      : apprenant.id === 'student-5' ? 80
      : apprenant.id === 'student-6' ? 0
      : apprenant.id === 'student-7' ? 100
      : apprenant.id === 'student-8' ? 55
      : apprenant.id === 'student-9' ? 90
      : apprenant.id === 'student-10' ? 30
      : 0;
    const niveau = progress >= 80 ? 'Avancé'
      : progress >= 40 ? 'Intermédiaire'
      : 'Débutant';
    const derniereFormation = apprenant.formations && apprenant.formations.length > 0
      ? apprenant.formations[apprenant.formations.length - 1]
      : '—';
    return {
      ...apprenant,
      derniereFormation,
      formationPrincipale,
      progress,
      niveau,
      formationProgression: apprenant.formations
        ? apprenant.formations.reduce((acc, f, idx) => {
            const p = Math.max(0, Math.min(100, progress + (idx * 10 - 20)));
            acc[f] = p;
            return acc;
          }, {})
        : {},
      profilComplete: apprenant.profilVerifie || false,
      telephone: apprenant.telephone || '—',
    };
  });

